"""System-One Multi, gold labels, step 1 of 3, on a Kaggle T4: build the training mix and the test suites from public datasets with gold
labels, check every training record against GLiNER2's processor, and score the base model and GLiNER2.5-multi-Decide on every suite.

Writes to the job's export folder:
- train.jsonl.gz, valid.jsonl.gz: GLiNER2 training records (`gold_example`), one JSON a line
- eval/rows.jsonl: the test rows, their gold kept; eval/answers/<model>.jsonl: each model's answers
- scores.json: each model's scores per suite; data.json: sources, counts, what was dropped and why

SCALE (environment, default 1) shrinks every count, for a quick end-to-end check.
"""
import gzip, json, os, random, re, time, warnings
from collections import Counter
from pathlib import Path

warnings.filterwarnings("ignore")
os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
import torch
import pyarrow.parquet as pq
import datasets
from datasets import load_dataset
from huggingface_hub import hf_hub_download, snapshot_download

from sysone.cloud import job_output
from sysone.distill import (BASE, DECIDE, MULTICONER_TYPES, CROSSNER_TYPES, hub_revision, load_extractor, tagged_rows, labelled_rows,
                            record_rows, fast_decision_rows, entity_row, nuner_mentions, sample_types, near_duplicates, parquet_rows)
from sysone.multitask import (jev_requests, jev_decision_row, jev_extraction_row, redfm_row, docred_rows, maven_ere_rows, maven_event_rows,
                              maven_arg_rows, event_roles, cnc_rows, nli_rows, copa_rows, market_rows, MARKET_KINDS, gold_example, spans_ok,
                              fits, cap, GoldCollator, answers, gold_scores, relation_families)

datasets.disable_progress_bars()
SCALE = float(os.environ.get("SCALE", "1"))
def n(k): return max(2, int(round(k * SCALE)))
OUT = job_output(Path("system-one-gold")); OUT.mkdir(parents=True, exist_ok=True)
T0 = time.time()
def say(*a): print(f"[{(time.time() - T0) / 60:5.1f} min]", *a, flush=True)
def write_jsonl(path, rows, gz=False):
    path = OUT / path; path.parent.mkdir(parents=True, exist_ok=True)
    with (gzip.open(path, "wt") if gz else open(path, "w")) as f:
        for r in rows: f.write((r if isinstance(r, str) else json.dumps(r, ensure_ascii=False)) + "\n")
def safe(name, f):
    "A source's rows, each tagged with it, or none when it fails to load: one bad source should not end the job"
    try:
        rows = f(); say(f"{name}: {len(rows):,} rows")
        return [r | {"dataset": name} for r in rows]
    except Exception as e:
        say(f"{name}: FAILED {type(e).__name__}: {str(e)[:300]}"); return []
def hub(repo, path, kind="dataset"): return hf_hub_download(repo, path, repo_type=kind)
def jsonl(path, most=None):
    out = []
    with open(path) as f:
        for line in f:
            out.append(json.loads(line))
            if most and len(out) >= most: break
    return out
JEV = "tasksource/tasksource-jev-typed-decisions"
def jev_table(path): return pq.read_table(hub(JEV, path)).to_pylist()

SOURCES = {"jev decisions": (JEV, "mixed, per row (license_use)"), "jev extraction": (JEV, "mixed, per row"),
           "typed-decisions": ("LocalLLaMA/typed-decisions", "Apache-2.0"), "massive": ("mteb/amazon_massive_intent", "CC BY 4.0"),
           "multiconer": ("MultiCoNER/multiconer_v2", "CC BY 4.0"), "nuner": ("numind/NuNER", "MIT"),
           "redfm": ("Babelscape/REDFM", "CC BY-SA 4.0"), "sredfm": ("Babelscape/SREDFM (English dev file)", "CC BY-SA 4.0"),
           "re-docred": ("tonytan48/Re-DocRED", "MIT"), "maven-ere": ("MaYiding/MAVEN-ERE (THU-KEG/MAVEN-ERE)", "GPL-3.0"),
           "maven-arg": ("mneb/maven-arg", "see its card"), "causal-news": ("thagen/CNCv2", "CC0 1.0"),
           "mnli": ("nyu-mll/multi_nli", "mostly OANC, see its card"), "e-care": ("12ml/e-CARE", "MIT"),
           "markets": ("generated by sysone.multitask.market_rows", "exact by construction"),
           "fast-decisions": ("fastino/fast-decisions", "Apache-2.0, test only"), "crossner": ("DFKI-SLT/cross_ner", "test only")}

# ---------------------------------------------------------------- the two models scored as the starting line, pinned
REV = {"base": hub_revision(BASE), "decide": hub_revision(DECIDE)}
say("models", REV)

# ---------------------------------------------------------------- decisions
def jev_train():
    rows = []
    for k in range(2):                                      # 2 of the 6 shards: groups are shuffled across shards, so they sample them all
        reqs = jev_requests(jev_table(f"data/train-0000{k}-of-00006.parquet"))
        rows += [r for q in reqs if (r := jev_decision_row(q)) and fits(r)]
    return cap(rows, n(120), seed=0)                        # at most 120 requests a source: decisions should not drown the rest

def jev_test():
    reqs = [q for q in jev_requests(jev_table("data/test-00000-of-00001.parquet")) if q.get("variant") == "direct"]
    rows = [r for q in reqs if (r := jev_decision_row(q, suite="jev decisions")) and fits(r)]
    return cap(rows, n(4), seed=1)

def typed(split, k, suite=None):
    ds = load_dataset("LocalLLaMA/typed-decisions", "all", split=split).shuffle(seed=0)
    return record_rows(list(ds.select(range(min(len(ds), n(k))))), keep_gold=True, suite=suite)

def massive(split, k, suite=None):
    ds = load_dataset("mteb/amazon_massive_intent", "en", split=split)
    return labelled_rows(ds, "text", "label_text", "intent", "massive-en", prompt="What does the user want?", names=sorted(set(ds["label_text"])),
                         lang="en", n=n(k), k=12 if suite is None else None, keep_gold=True, suite=suite)

def fast_decisions():
    repo = Path(snapshot_download("fastino/fast-decisions", repo_type="dataset"))
    return [r for f in sorted(repo.glob("*.jsonl")) for r in fast_decision_rows([json.loads(l) for l in f.read_text().splitlines()][:n(100)], f.stem)]

# ---------------------------------------------------------------- entities and spans
def jev_spans(path, most, suite=None):
    rows = [r for x in jev_table(path) if (r := jev_extraction_row(x, suite=suite)) and fits(r)]
    return cap(rows, most, seed=2)

def multiconer(split, k, suite=None):
    ds = parquet_rows("MultiCoNER/multiconer_v2", "English (EN)", split, n=n(k), seed=0)
    return tagged_rows(ds, MULTICONER_TYPES, "multiconer-en", "en", gold=True, all_types=suite is not None, suite=suite, seed=3)

def nuner(k):
    rng = random.Random(4); rows = parquet_rows("numind/NuNER", "default", "entity", n=n(k), seed=0)
    found = [nuner_mentions(r["output"]) for r in rows]
    pool = sorted({t for f in found for t in f})
    return [entity_row(f"nuner/{i}", r["input"], f, sample_types(list(f), pool, rng), "nuner", "en", gold=True)
            for i, (r, f) in enumerate(zip(rows, found)) if f]

def crossner_test():
    rows = []
    for dom in ("ai", "literature", "music", "politics", "science"):
        ds = parquet_rows("DFKI-SLT/cross_ner", dom, "test", n=n(80), seed=0)
        names = ds.features["ner_tags"].feature.names
        types = [CROSSNER_TYPES.get(c, c) for c in sorted({names[t][2:] for r in ds for t in r["ner_tags"] if names[t] != "O"})]
        rows += tagged_rows(ds, CROSSNER_TYPES, f"crossner-{dom}", "en", gold=True, all_types=True, types=types, suite="crossner")
    return rows

# ---------------------------------------------------------------- relations between entities
REDFM_POOL = []
def redfm(path, source, most, suite=None, seed=5):
    recs = jsonl(hub("Babelscape/" + ("SREDFM" if source == "sredfm" else "REDFM"), path), most=most)
    REDFM_POOL.extend(sorted({(x.get("predicate") or {}).get("surfaceform", "").strip().lower() for r in recs for x in r["relations"]} - {""}))
    pool, rng = sorted(set(REDFM_POOL)), random.Random(seed)
    return [x for r in recs if (x := redfm_row(r, source, pool, rng, suite=suite)) and fits(x)]

def docred(split_file, k, suite=None, seed=6):
    names = json.loads(gzip.open(hub("thunlp/docred", "data/rel_info.json.gz")).read())
    docs = json.load(open(hub("tonytan48/Re-DocRED", split_file)))
    rng = random.Random(seed); docs = rng.sample(docs, min(len(docs), n(k)))
    return [x for d in docs for x in docred_rows(d, names, sorted(names.values()), rng, suite=suite) if fits(x)]

# ---------------------------------------------------------------- events
MAVEN = {}
def maven_docs(split):
    if split not in MAVEN: MAVEN[split] = jsonl(hub("MaYiding/MAVEN-ERE", f"{split}.jsonl"))
    return MAVEN[split]

def maven_types():
    return sorted({ev["type"].replace("_", " ").lower() for d in maven_docs("train") for ev in d.get("events") or []})

def maven_ere(split, k, suite=None, seed=7):
    rng = random.Random(seed); docs = maven_docs(split); docs = rng.sample(docs, min(len(docs), n(k)))
    return [x for d in docs for x in maven_ere_rows(d, rng=rng, suite=suite) if fits(x)]

def maven_events(split, k, suite=None, seed=8):
    rng = random.Random(seed); docs = maven_docs(split); docs = rng.sample(docs, min(len(docs), n(k))); pool = maven_types()
    return [x for d in docs for x in maven_event_rows(d, pool, rng, suite=suite) if fits(x)]

def maven_arg(split, k, suite=None, seed=9):
    train = jsonl(hub("mneb/maven-arg", "data/maven_arg_train.jsonl"))
    roles = event_roles(train)
    rows = train if split == "train" else jsonl(hub("mneb/maven-arg", "data/maven_arg_validation.jsonl"))
    rng = random.Random(seed); rows = rng.sample(rows, min(len(rows), n(k)))
    return [x for i, r in enumerate(rows) for x in maven_arg_rows(r | {"id": i}, roles, rng, suite=suite) if fits(x)]

# ---------------------------------------------------------------- statements: implies, rules out, causes, is a precondition of
def mnli(split, k, suite=None, seed=11):
    rows = pq.read_table(hub("nyu-mll/multi_nli", f"data/{split}-00000-of-00001.parquet"), columns=["premise", "hypothesis", "label"]).to_pylist()
    rng = random.Random(seed); keep = set(rng.sample(sorted({r["premise"] for r in rows}), min(n(k), len({r["premise"] for r in rows}))))
    return [x for x in nli_rows([r for r in rows if r["premise"] in keep], rng, suite=suite) if fits(x)]

def ecare(split, k, suite=None, seed=12):
    import csv
    rows = list(csv.DictReader(open(hub("12ml/e-CARE", f"{split}.csv"))))
    rng = random.Random(seed); rows = rng.sample(rows, min(len(rows), n(k)))
    return [x for x in copa_rows(rows, rng, suite=suite) if fits(x)]

def markets(k, part, kinds=MARKET_KINDS[:-1], suite=None, seed=13): return [x for x in market_rows(n(k), seed=seed, part=part, kinds=kinds, suite=suite) if fits(x)]

def causal_news(split, suite=None):
    return [x for x in cnc_rows(pq.read_table(hub("thagen/CNCv2", f"causality-identification/{split}.parquet")).to_pylist(),
                                suite=suite) if fits(x)]

# ---------------------------------------------------------------- the test suites (gold kept), then the training rows
say("test suites")
EVAL = []
for name, f in [("fast-decisions", fast_decisions), ("typed-decisions test", lambda: typed("test", 200, "typed-decisions")),
                ("MASSIVE en test", lambda: massive("test", 300, "massive")), ("jev decisions test", jev_test),
                ("MultiCoNER en test", lambda: multiconer("test", 300, "multiconer")), ("CrossNER test", crossner_test),
                ("jev spans test", lambda: jev_spans("extraction/test-00000-of-00001.parquet", n(8), "jev spans")),
                ("REDFM en test", lambda: redfm("data/test.en.jsonl", "redfm", None, "redfm")),
                ("Re-DocRED test", lambda: docred("test_revised.json", 300, "re-docred")),
                ("MAVEN-ERE valid", lambda: maven_ere("valid", 250, "maven-ere")),
                ("MAVEN event types valid", lambda: maven_events("valid", 150, "maven event types")),
                ("MAVEN-Arg valid", lambda: maven_arg("validation", 150, "maven-arg")),
                ("Causal News dev", lambda: causal_news("dev", "causal news")),
                ("MNLI statements (validation)", lambda: mnli("validation_matched", 600, "mnli statements")),
                ("e-CARE statements (validation)", lambda: ecare("validation", 750, "e-care statements")),
                ("markets, kinds seen in training", lambda: markets(300, "test", suite="markets")),
                ("markets, ranges (never trained on)", lambda: markets(150, "test", kinds=("ranges",), suite="markets (ranges)"))]:
    EVAL += safe(name, f)
for r in EVAL:
    if r.get("suite") == "jev spans": r["suite"] = "jev records" if r["ask"].get("structures") else "jev entities"
say("test rows by suite:", dict(Counter(r["suite"] for r in EVAL)))

say("training sources")
TRAIN = []
for name, f in [("jev decisions", jev_train), ("typed-decisions train", lambda: typed("train", 2000)),
                ("MASSIVE en train", lambda: massive("train", 3000)),
                ("jev spans", lambda: jev_spans("extraction/train-00000-of-00005.parquet", n(250))),
                ("MultiCoNER en train", lambda: multiconer("train", 6000)), ("NuNER", lambda: nuner(15000)),
                ("REDFM en train", lambda: redfm("data/train.en.jsonl", "redfm", None)),
                ("SREDFM en", lambda: redfm("data/dev.en.jsonl", "sredfm", n(15000))),
                ("Re-DocRED train", lambda: docred("train_revised.json", 4000)),
                ("MAVEN-ERE train", lambda: maven_ere("train", 3000)), ("MAVEN event types train", lambda: maven_events("train", 3000)),
                ("MAVEN-Arg train", lambda: maven_arg("train", 3000)), ("Causal News train", lambda: causal_news("train")),
                ("MNLI statements", lambda: mnli("train", 12000)), ("e-CARE statements", lambda: ecare("train", 14000)),
                ("market lists", lambda: markets(8000, "train"))]:
    TRAIN += safe(name, f)

# ---------------------------------------------------------------- no test text in training: exact and near duplicates dropped
norm = lambda t: re.sub(r"\s+", " ", t).strip().lower()
seen = {norm(r["text"]) for r in EVAL}
exact = [r for r in TRAIN if norm(r["text"]) in seen]
TRAIN = [r for r in TRAIN if norm(r["text"]) not in seen]
near = near_duplicates([r["text"] for r in TRAIN], [r["text"] for r in EVAL])
TRAIN = [r for i, r in enumerate(TRAIN) if i not in near]
say(f"dropped {len(exact):,} training rows whose text is a test row's, and {len(near):,} near duplicates")

# ---------------------------------------------------------------- training records, each checked by GLiNER2's processor
base = load_extractor(BASE, revision=REV["base"])
check = GoldCollator(base.processor, train=False, drop=False)
records, refused = [], Counter()
for r in TRAIN:
    e = gold_example(r) | {"dataset": r["dataset"]}
    if not spans_ok(e): refused[(r["dataset"], "span offsets")] += 1; continue
    records.append(e)
good = []
for s in range(0, len(records), 64):
    chunk = records[s:s + 64]
    try: check([(e, 0) for e in chunk]); good += chunk
    except Exception:
        for e in chunk:
            try: check([(e, 0)]); good.append(e)
            except Exception as x: refused[(e["dataset"], type(x).__name__)] += 1
say(f"{len(good):,} training records; refused: {dict(Counter({f'{a}: {b}': v for (a, b), v in refused.items()}))}")
rng = random.Random(10); rng.shuffle(good)
k = min(3000, max(16, len(good) // 50))
valid, train = good[:k], good[k:]
write_jsonl("train.jsonl.gz", [json.dumps(e, ensure_ascii=False) for e in train], gz=True)
write_jsonl("valid.jsonl.gz", [json.dumps(e, ensure_ascii=False) for e in valid], gz=True)
write_jsonl("eval/rows.jsonl", EVAL)
data = {"models": {"base": f"{BASE}@{REV['base']}", "decide": f"{DECIDE}@{REV['decide']}"}, "scale": SCALE,
        "sources": {k: {"repo": v[0], "license": v[1]} for k, v in SOURCES.items()},
        "train": dict(Counter(e["dataset"] for e in train)), "jev_sources": len({e["source"] for e in train if e["dataset"].startswith("jev")}),
        "train_kinds": dict(Counter(e["kind"] for e in train)), "train_rows": len(train), "valid_rows": len(valid),
        "eval": dict(Counter(r["suite"] for r in EVAL)), "dropped": {"exact": len(exact), "near": len(near),
        "refused": {f"{a}: {b}": v for (a, b), v in refused.items()}}}
(OUT / "data.json").write_text(json.dumps(data, indent=1))
say("written", {p.name: f"{p.stat().st_size / 1e6:.1f} MB" for p in OUT.rglob("*") if p.is_file()})

# ---------------------------------------------------------------- the starting line: both models on every suite
fam, scores = relation_families(), {}
for name, (repo, rev) in {"gliner2.5-multi-v1 (base)": (BASE, REV["base"]), "GLiNER2.5-multi-Decide": (DECIDE, REV["decide"])}.items():
    model = base if repo == BASE else load_extractor(repo, revision=rev)
    model.to("cuda" if torch.cuda.is_available() else "cpu").eval()
    t = time.time(); got = answers(model, EVAL, batch_size=8, max_tokens=6144)
    write_jsonl(f"eval/answers/{name}.jsonl", got)
    scores[name] = gold_scores(got, EVAL, families=fam)
    say(f"{name}: answered {len(EVAL):,} rows in {(time.time() - t) / 60:.1f} min")
    for suite, s in scores[name].items():
        say(f"   {suite:20}", {k: round(v, 3) for k, v in s.items() if isinstance(v, float) and not k.endswith(("_p", "_r")) and "~" not in k})
    (OUT / "scores.json").write_text(json.dumps(scores, indent=1))
    del model; torch.cuda.empty_cache()
say("done")
